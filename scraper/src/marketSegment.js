// Определяет сегмент рынка ("вторичный рынок" / "новостройка") по
// тексту объявления (метка "новостройка/вторичка"). В Ташкенте, особенно
// в центральных районах (Шайхантахурский, Юнусабадский и т.п.), в
// ОДНОМ районе одновременно продаются дешёвая старая вторичка
// (~$800-1500/м²) и элитные новостройки/ЖК (~$3000-5000+/м²). Без
// разделения одно-два объявления из новостройки в маленькой выборке
// (MIN_SAMPLE=5-8) утягивают медиану района вверх — и обычная
// вторичка начинает ложно выглядеть "на 40-50% дешевле рынка".
//
// Сознательно НЕ используем более широкие эвристики (например, слово
// "ЖК" — часто просто ориентир типа "рядом с ЖК Х", а не сам продаваемый
// объект) — точность важнее полноты охвата: пустой результат (null)
// безопасен (метка просто не показывается), а вот ложное определение
// сегмента вводит в заблуждение сильнее, чем его отсутствие.
const NEW_BUILD_RE = /новостройк[а-я]*/i;
const SECONDARY_RE = /вторичн(?:ый|ого|ом)?\s*рынок[а-я]*/i;

/**
 * @param {string|null|undefined} text — любой доступный текст объявления
 *   (характеристики карточки, описание, заголовок — чем больше, тем
 *   выше шанс поймать явную фразу).
 * @returns {'new_build'|'secondary'|null}
 */
export function detectMarketSegment(text) {
  if (!text) return null;
  if (NEW_BUILD_RE.test(text)) return 'new_build';
  if (SECONDARY_RE.test(text)) return 'secondary';
  return null;
}
